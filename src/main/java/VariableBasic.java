void main() {
    // 변수 선언과 할당
    int age = 20;
    System.out.println(age);

    // 변수 값 변경
    age = 21;
    System.out.println(age);

    // 여러 변수 선언
    int birthYear = 2006;
    int currentYear = 2026;
    System.out.println(currentYear - birthYear);

    // 변수 이름 짓기 — camelCase
    int myFavoriteNumber = 7;
    System.out.println(myFavoriteNumber);
}
